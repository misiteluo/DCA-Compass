function ManualTable({ title, headers, rows, caption = false }: {
  title: string;
  headers: string[];
  rows: string[][];
  caption?: boolean;
}) {
  return (
    <div className="table-scroll" role="region" aria-label={title} tabIndex={0}>
      <table style={{ minWidth: headers.length < 5 ? 0 : undefined }}>
        {caption && <caption style={{ textAlign: "left", fontWeight: 600 }}>{title}</caption>}
        <thead><tr>{headers.map((header) => <th key={header} scope="col">{header}</th>)}</tr></thead>
        <tbody>{rows.map(([label, ...cells]) => (
          <tr key={label}>
            <th scope="row">{label}</th>
            {cells.map((cell, index) => <td key={headers[index + 1]}>{cell}</td>)}
          </tr>
        ))}</tbody>
      </table>
    </div>
  );
}

